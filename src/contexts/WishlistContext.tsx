import React, { createContext, useContext, useEffect, useState } from 'react';
import { Product } from '../types/product';
import { getStorageItem, setStorageItem } from '../utils/storage';
import { PRODUCTS } from '../data/products';

interface WishlistContextType {
  wishlist: Product[];
  toggleWishlist: (product: Product) => void;
  isInWishlist: (productId: string) => boolean;
  removeFromWishlist: (productId: string) => void;
  clearWishlist: () => void;
}

const STORAGE_KEY = 'dura_luxury_wishlist';

// Default with a couple of favorites for immediate visual richness
const DEFAULT_INITIAL_WISHLIST: Product[] = [
  PRODUCTS[2], // Elegant Gold Hoops
  PRODUCTS[6], // Dainty Pearl Bracelet
];

const WishlistContext = createContext<WishlistContextType | undefined>(undefined);

export const WishlistProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [wishlist, setWishlist] = useState<Product[]>(() => {
    return getStorageItem<Product[]>(STORAGE_KEY, DEFAULT_INITIAL_WISHLIST);
  });

  useEffect(() => {
    setStorageItem(STORAGE_KEY, wishlist);
  }, [wishlist]);

  const toggleWishlist = (product: Product) => {
    setWishlist((prev) => {
      const exists = prev.some((p) => p.id === product.id);
      if (exists) {
        return prev.filter((p) => p.id !== product.id);
      }
      return [...prev, product];
    });
  };

  const isInWishlist = (productId: string) => {
    return wishlist.some((p) => p.id === productId);
  };

  const removeFromWishlist = (productId: string) => {
    setWishlist((prev) => prev.filter((p) => p.id !== productId));
  };

  const clearWishlist = () => {
    setWishlist([]);
  };

  return (
    <WishlistContext.Provider
      value={{
        wishlist,
        toggleWishlist,
        isInWishlist,
        removeFromWishlist,
        clearWishlist,
      }}
    >
      {children}
    </WishlistContext.Provider>
  );
};

export const useWishlist = () => {
  const context = useContext(WishlistContext);
  if (!context) {
    throw new Error('useWishlist must be used within a WishlistProvider');
  }
  return context;
};
